"""Disposable, incremental SQLite search projection of the authoritative Git tree.

Only changed blobs are decoded. Warm queries read bounded FTS candidates, never
all Markdown or the link graph. A SQLite transaction publishes one complete
projection; independent REST/MCP processes observe the same durable revision.
"""

from __future__ import annotations

import json
import math
import sqlite3
from collections.abc import Iterator
from contextlib import contextmanager
from typing import TYPE_CHECKING, Any

from second_brain.wiki.relevance import (
    HEADING_RE,
    content_tokens,
    rank_pages,
    tokenize,
)

if TYPE_CHECKING:
    from second_brain.wiki.store import WikiStore


class SearchView:
    """One immutable read transaction. Page bodies are loaded only for candidates."""

    def __init__(self, db: sqlite3.Connection, revision: str) -> None:
        self.db = db
        self.revision = revision

    def pages(self, ids: list[str]) -> list[dict[str, Any]]:
        if not ids:
            return []
        marks = ",".join("?" for _ in ids)
        rows = self.db.execute(f"SELECT page FROM documents WHERE id IN ({marks})", ids)
        return [json.loads(row[0]) for row in rows]

    def frequency(self, token: str) -> int:
        row = self.db.execute("SELECT doc FROM vocabulary WHERE term=?", (token,)).fetchone()
        return int(row[0]) if row else 0

    def contains(self, page_id: str, token: str) -> bool:
        return self.db.execute(
            "SELECT 1 FROM terms JOIN documents d ON d.rowid=terms.rowid "
            "WHERE terms MATCH ? AND d.id=? LIMIT 1",
            ('"' + token + '"', page_id),
        ).fetchone() is not None

    def weights(self, query: str) -> dict[str, float]:
        total = int(self.db.execute("SELECT count(*) FROM documents").fetchone()[0])
        weights = {}
        for token in set(content_tokens(query)):
            count = self.frequency(token)
            weights[token] = math.log(1.0 + (total - count + 0.5) / (count + 0.5))
        peak = max(weights.values(), default=0.0)
        return {token: weight / peak if peak else 1.0 for token, weight in weights.items()}

    def lexical(self, query: str, limit: int) -> list[dict[str, Any]]:
        tokens = content_tokens(query)
        if not tokens:
            return []
        # Tokens are generated by our tokenizer; quote even those so user input
        # can never become FTS operators. Prefix matching preserves title lookup.
        match = " OR ".join('"' + token + '"*' for token in set(tokens))
        maximum = max(100, limit * 4)
        rows = self.db.execute(
            "SELECT d.page FROM terms JOIN documents d ON d.rowid=terms.rowid "
            "WHERE terms MATCH ? ORDER BY bm25(terms,6,5,3,1),d.id LIMIT ?",
            (match, maximum),
        )
        candidates = {page["id"]: page for page in (json.loads(row[0]) for row in rows)}
        # Exact identity must not disappear behind a large set of body matches.
        identities = [query.strip().casefold(), *tokens]
        marks = ",".join("?" for _ in identities)
        for row in self.db.execute(
            f"SELECT page FROM documents WHERE title_key IN ({marks}) OR id IN ({marks})",
            [*identities, *identities],
        ):
            page = json.loads(row[0])
            candidates[page["id"]] = page
        ranked = rank_pages(query, list(candidates.values()), {}, token_weights=self.weights(query))
        ranked = [page for page in ranked if float(page["rank_score"]) > 0]
        exact = query.strip().casefold()
        ranked.sort(
            key=lambda page: (
                exact not in {page["id"].casefold(), page["title"].casefold()},
                -float(page["rank_score"]),
                page["title"].casefold(),
                page["id"],
            )
        )
        return ranked[:limit]


class SearchCatalog:
    def __init__(self, store: WikiStore) -> None:
        self.store = store
        self.path = store.path / ".wiki-search.sqlite3"
        with self._db() as db:
            db.execute("PRAGMA journal_mode=WAL")
            db.execute("CREATE TABLE IF NOT EXISTS metadata (key TEXT PRIMARY KEY,value TEXT)")
            db.execute(
                "CREATE TABLE IF NOT EXISTS documents (id TEXT UNIQUE,blob TEXT,"
                "revision_blob TEXT,title_key TEXT,page TEXT)"
            )
            db.execute("CREATE INDEX IF NOT EXISTS document_title ON documents(title_key)")
            db.execute(
                "CREATE VIRTUAL TABLE IF NOT EXISTS terms USING fts5("
                "title,ident,headings,body,tokenize='unicode61 remove_diacritics 0')"
            )
            db.execute("CREATE VIRTUAL TABLE IF NOT EXISTS vocabulary USING fts5vocab(terms,'row')")

    @contextmanager
    def _db(self) -> Iterator[sqlite3.Connection]:
        db = sqlite3.connect(self.path, timeout=30)
        try:
            with db:
                yield db
        finally:
            db.close()

    @staticmethod
    def _revision(db: sqlite3.Connection) -> str | None:
        row = db.execute("SELECT value FROM metadata WHERE key='revision'").fetchone()
        return str(row[0]) if row else None

    def _refresh(self, db: sqlite3.Connection) -> None:
        # A second process may have refreshed while we waited for the writer.
        db.execute("BEGIN IMMEDIATE")
        head = self.store._head()
        if self._revision(db) == head:
            db.commit()
            return
        entries = self.store._tree_blobs(head, "pages/", "revisions/")
        old = {
            row[0]: row[1:]
            for row in db.execute("SELECT id,rowid,blob,revision_blob FROM documents")
        }
        current = {
            path.removeprefix("pages/").removesuffix(".md"): sha
            for path, sha in entries.items()
            if path.startswith("pages/") and path.endswith(".md")
        }
        changed = {
            page_id: sha
            for page_id, sha in current.items()
            if page_id not in old
            or old[page_id][1] != sha.decode()
            or old[page_id][2] != entries.get(f"revisions/{page_id}", b"").decode()
        }
        wanted = {
            path: sha
            for page_id, sha in changed.items()
            for path, sha in (
                (f"pages/{page_id}.md", sha),
                (f"revisions/{page_id}", entries.get(f"revisions/{page_id}", b"")),
            )
            if sha
        }
        blobs = self.store._read_blobs(wanted)
        for page_id in old.keys() - current.keys() | changed.keys():
            previous = old.get(page_id)
            if previous:
                db.execute("DELETE FROM terms WHERE rowid=?", (previous[0],))
                db.execute("DELETE FROM documents WHERE id=?", (page_id,))
        for page_id, sha in changed.items():
            revision = blobs.get(f"revisions/{page_id}", b"").decode()
            page = self.store._page(page_id, blobs[f"pages/{page_id}.md"], revision)
            cursor = db.execute(
                "INSERT INTO documents VALUES (?,?,?,?,?)",
                (
                    page_id,
                    sha.decode(),
                    entries.get(f"revisions/{page_id}", b"").decode(),
                    page["title"].casefold(),
                    json.dumps(page, ensure_ascii=False),
                ),
            )
            title = page["title"]
            headings = " ".join(
                sorted(
                    {
                        token
                        for heading in HEADING_RE.findall(page["markdown"])
                        if heading.casefold().strip() != title.casefold().strip()
                        for token in tokenize(heading)
                    }
                )
            )
            db.execute(
                "INSERT INTO terms(rowid,title,ident,headings,body) VALUES (?,?,?,?,?)",
                (
                    cursor.lastrowid,
                    " ".join(tokenize(title)),
                    " ".join(tokenize(page_id)),
                    headings,
                    " ".join(tokenize(page["markdown"])[:4000]),
                ),
            )
        db.execute("INSERT OR REPLACE INTO metadata VALUES ('revision',?)", (head,))
        db.commit()

    @contextmanager
    def read(self) -> Iterator[SearchView]:
        with self._db() as db:
            if self._revision(db) != self.store._head():
                self._refresh(db)
            db.execute("BEGIN")
            yield SearchView(db, self._revision(db) or "")
